"""
You are given two strings s and t. String t is generated by randomly shuffling string s 
and then adding one more letter at a random position. Return the letter that was added to t.

Examples:
s = "abcd", t = "abcde" → "e"
s = "", t = "y" → "y"
s = "a", t = "aa" → "a"
"""

def find_diff(s: str, t: str) -> str:
	count = {}

	for char in s:
		count[char] = count.get(char, 0) + 1

	for char in t:
		if char not in count or count[char] == 0:
			return char
		count[char] -= 1	

print(find_diff("abcd", "abcde"))
print(find_diff("", "y"))
print(find_diff("a", "aa"))	
